import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { PACKAGE_ROOT } from '../src/renderer.js';
import { FALLBACK_FONTS } from '../src/remotion/scripts.js';

/**
 * Writes src/remotion/fallback-fonts.css from the @fontsource packages in
 * FALLBACK_FONTS: one @font-face per subset the family needs (the script's own
 * subsets; Inter already draws Latin, Greek and Cyrillic), woff2 only, under Kilo's
 * own family names, so the page never falls back to a font of the machine.
 * `npm run fonts` after changing FALLBACK_FONTS or a package version.
 */
const OUT = path.join(PACKAGE_ROOT, 'src', 'remotion', 'fallback-fonts.css');
const FROM = path.dirname(OUT);

const blocks: string[] = [];
let faces = 0;
for (const f of FALLBACK_FONTS) {
  const pkgDir = path.join(PACKAGE_ROOT, 'node_modules', f.pkg);
  const version = (JSON.parse(readFileSync(path.join(pkgDir, 'package.json'), 'utf8')) as { version: string }).version;
  const css = readFileSync(path.join(pkgDir, f.css), 'utf8');
  const re = /\/\*\s*([^*]+?)\s*\*\/\s*@font-face\s*\{([^}]*)\}/g;
  let kept = 0;
  for (const m of css.matchAll(re)) {
    const name = m[1]!;
    const body = m[2]!;
    // "noto-sans-jp-[12]-wght-normal" -> "12"; "noto-sans-arabic-arabic-wght-normal" -> "arabic".
    const base = f.pkg.split('/').pop()!;
    const subset = name.startsWith(`${base}-`) ? name.slice(base.length + 1).replace(/-(?:wght|\d+)-normal$/, '').replace(/^\[|\]$/g, '') : name;
    if (!f.subsets(subset)) continue;
    const woff2 = /url\(\.\/files\/([^)]+\.woff2)\)\s*format\('([^']+)'\)/.exec(body);
    const range = /unicode-range:\s*([^;]+);/.exec(body)?.[1]?.trim();
    const weight = /font-weight:\s*([^;]+);/.exec(body)?.[1]?.trim() ?? '400';
    if (!woff2) throw new Error(`${f.pkg}: no woff2 in ${name}`);
    const url = path.relative(FROM, path.join(pkgDir, 'files', woff2[1]!)).split(path.sep).join('/');
    blocks.push(
      `/* ${f.pkg}@${version} ${subset} */\n@font-face {\n  font-family: '${f.family}';\n  font-style: normal;\n  font-display: block;\n` +
        `  font-weight: ${weight};\n  src: url(${url}) format('${woff2[2]}');\n${range ? `  unicode-range: ${range};\n` : ''}}\n`,
    );
    kept++;
  }
  if (!kept) throw new Error(`${f.pkg}: no subset kept`);
  faces += kept;
  console.log(`${f.family}: ${kept} faces from ${f.pkg}@${version}`);
}
writeFileSync(
  OUT,
  `/* Generated by scripts/gen-fallback-fonts.ts from the @fontsource packages (SIL Open Font License 1.1). Do not edit. */\n\n${blocks.join('\n')}`,
);
console.log(`${faces} faces -> ${path.relative(PACKAGE_ROOT, OUT)}`);
